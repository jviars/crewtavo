#!/usr/bin/env bash
# Regenerates packages/core/src/database.types.ts from supabase/migrations using a throwaway
# Postgres in Docker (no Supabase project needed).   npm run db:types
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NAME="crewtavo-typegen-$$"
PORT="${PORT:-54329}"
cleanup() { docker rm -f "$NAME" >/dev/null 2>&1 || true; }
trap cleanup EXIT

docker run -d --name "$NAME" -e POSTGRES_PASSWORD=postgres -p "$PORT:5432" postgres:17-alpine >/dev/null
for _ in $(seq 1 60); do docker exec "$NAME" pg_isready -U postgres -q && break; sleep 0.5; done
sleep 1
cat "$ROOT/supabase/tests/prelude.sql" "$ROOT"/supabase/migrations/*.sql \
  | docker exec -i "$NAME" psql -U postgres -v ON_ERROR_STOP=1 -q -o /dev/null 2>/dev/null

OUT="$ROOT/packages/core/src/database.types.ts"
{
  echo "// Generated by scripts/gen-types.sh from supabase/migrations. Do not edit by hand."
  npx -y supabase@2.121.0 gen types typescript --db-url "postgresql://postgres:postgres@localhost:$PORT/postgres?sslmode=disable" --schema public
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT"
